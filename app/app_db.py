"""
Writable application database: user accounts and login attempts.

Kept apart from the analytics database (uhai_dashboard.db), which db.py opens
read-only and which this module never touches.

  Locally  a SQLite file next to the app folder (uhai_app.db, not in git).
  Live     PostgreSQL (Neon) when DATABASE_URL is set.

SQL is written once, with ? placeholders and types both databases accept
(TEXT dates in ISO format, INSERT ... ON CONFLICT, INSERT ... RETURNING).
This module adapts it for PostgreSQL.
"""

import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent

# Override with UHAI_APP_DB to keep the SQLite file elsewhere (e.g. a test copy).
APP_DB_PATH = Path(os.environ.get("UHAI_APP_DB", BASE_DIR / "uhai_app.db"))

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

# Auto-numbered primary key, for CREATE TABLE statements.
ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if POSTGRES else "INTEGER PRIMARY KEY AUTOINCREMENT"


def describe():
    """Which database is in use, without revealing the connection string."""
    return "PostgreSQL (DATABASE_URL)" if POSTGRES else f"SQLite ({APP_DB_PATH.name})"


def _pg(sql):
    """? placeholders -> %s; a literal % must be doubled for psycopg."""
    return sql.replace("%", "%%").replace("?", "%s")


class _PgConnection:
    """The small sqlite3-like surface this app uses, on top of psycopg."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, params=()):
        return self.raw.execute(_pg(sql), tuple(params))

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect():
    if POSTGRES:
        import psycopg  # only needed live

        return _PgConnection(psycopg.connect(DATABASE_URL, connect_timeout=10))

    connection = sqlite3.connect(APP_DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def query(sql, params=()):
    """
    Execute a SELECT query and return the results as dictionaries.
    """
    connection = connect()

    try:
        cursor = connection.execute(sql, params)

        if POSTGRES:
            columns = [c.name for c in cursor.description]
            return [dict(zip(columns, row)) for row in cursor.fetchall()]

        return [dict(row) for row in cursor.fetchall()]

    finally:
        connection.close()


@contextmanager
def transaction():
    """
    Run several statements as one unit: all are saved, or none are.
    """
    connection = connect()

    try:
        yield connection
        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


# Any fixed number: PostgreSQL advisory-lock key shared by every app process.
_MIGRATION_LOCK = 727_001


def _lock(connection):
    """
    Let one process at a time change the tables. Render starts several gunicorn
    workers at once; without this they could race to create the same tables.
    SQLite gets the same effect from BEGIN IMMEDIATE.
    """
    if POSTGRES:
        connection.execute("SELECT pg_advisory_xact_lock(?)", (_MIGRATION_LOCK,))


def migrate(steps):
    """
    Bring the database up to date. steps is a list of (name, function); each
    function receives an open connection and runs inside one transaction, so a
    step is either fully applied or not at all. Applied steps are recorded in
    app_migrations and never run twice.
    """
    with transaction() as connection:
        _lock(connection)
        connection.execute(
            "CREATE TABLE IF NOT EXISTS app_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)"
        )

    done = {row["name"] for row in query("SELECT name FROM app_migrations")}

    for name, step in steps:
        if name in done:
            continue

        connection = connect()

        # sqlite3 would otherwise commit CREATE/ALTER at once, leaving a
        # half-applied step if a later statement failed. PostgreSQL already
        # runs DDL inside the transaction.
        if not POSTGRES:
            connection.isolation_level = None
            connection.execute("BEGIN IMMEDIATE")

        try:
            _lock(connection)

            # Another worker may have applied it while this one waited for the lock.
            if connection.execute("SELECT 1 FROM app_migrations WHERE name = ?", (name,)).fetchone():
                if POSTGRES:
                    connection.commit()
                else:
                    connection.execute("COMMIT")
                continue

            step(connection)
            connection.execute(
                "INSERT INTO app_migrations (name, applied_at) VALUES (?, ?)",
                (name, datetime.now(timezone.utc).isoformat(timespec="seconds")),
            )
            if POSTGRES:
                connection.commit()
            else:
                connection.execute("COMMIT")

        except Exception:
            if POSTGRES:
                connection.rollback()
            else:
                connection.execute("ROLLBACK")
            raise

        finally:
            connection.close()
